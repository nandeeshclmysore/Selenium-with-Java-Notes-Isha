package JavaForRestassured;

public class ConditionalStatements1 {
    public static void main(String[] args) {
        int a=103;

        if(a==10){
            System.out.println("a value is 10");
        }
        else if(a>10){
            System.out.println("a value is greater than 10");
        }
        else {
            System.out.println("a value is lesser than 10");
        }
    }
}
